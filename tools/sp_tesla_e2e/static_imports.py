#!/usr/bin/env python3
"""Static import check for large deletions. Uses only stdlib, because the host has no native env.

Failure cases listed before implementation:
- I1 a kept module imports a deleted module (openpilot.*, opendbc.*, panda.*, teleoprtc.*).
- I2 `from pkg import name` where name is neither a submodule nor a top-level name of pkg.
- I3 the process table names a PythonProcess module or NativeProcess directory that no longer exists.
Imports inside try/except ImportError (or Exception) are optional and are skipped.
A module that does `from x import *` accepts any name, because static resolution stops there.
"""
import ast
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
PACKAGES = {"openpilot": ROOT / "openpilot", "opendbc": ROOT / "opendbc_repo/opendbc",
            "panda": ROOT / "panda", "teleoprtc": ROOT / "teleoprtc_repo/teleoprtc"}
SCAN = [ROOT / "openpilot", ROOT / "opendbc_repo/opendbc", ROOT / "panda", ROOT / "tools"]
# Modules generated by the native build (scons/cython/acados); they never exist in a clean checkout.
GENERATED = ("c_generated_code", "params_pyx", "transformations", "cereal.gen", "libsafety")
PROCESS_FILES = [ROOT / "openpilot/system/manager/process_config.py", *ROOT.glob("openpilot/sunnypilot/system/fork_processes.py"),
                 *ROOT.glob("openpilot/tesla/processes.py")]


def module_path(name: str) -> Path | None:
  parts = name.split(".")
  if parts[0] not in PACKAGES:
    return None
  base = PACKAGES[parts[0]].joinpath(*parts[1:])
  for p in (base.with_suffix(".py"), base / "__init__.py", base.with_suffix(".pyx")):
    if p.is_file():
      return p
  return base if base.is_dir() else None


_names: dict[Path, set[str] | None] = {}


def top_names(path: Path) -> set[str] | None:
  """Top-level names of a module; None means `import *` makes it permissive."""
  if path not in _names:
    names: set[str] | None = set()
    if path.is_file() and path.suffix == ".py":
      for node in ast.parse(path.read_text(errors="replace")).body:
        for n in ast.walk(node) if isinstance(node, (ast.If, ast.Try, ast.With)) else [node]:
          if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            names.add(n.name)
          elif isinstance(n, (ast.Assign, ast.AnnAssign, ast.AugAssign)):
            for t in (n.targets if isinstance(n, ast.Assign) else [n.target]):
              names |= {e.id for e in ast.walk(t) if isinstance(e, ast.Name)}
          elif isinstance(n, (ast.Import, ast.ImportFrom)):
            if any(a.name == "*" for a in n.names):
              names = None
              break
            names |= {(a.asname or a.name).split(".")[0] for a in n.names}
        if names is None:
          break
    elif path.suffix == ".pyx" or path.is_dir():
      names = None  # compiled module or namespace package: cannot enumerate
    _names[path] = names
  return _names[path]


def optional_lines(tree: ast.AST) -> set[int]:
  lines: set[int] = set()
  for node in ast.walk(tree):
    if isinstance(node, ast.Try) and any(h.type is None or any(isinstance(e, ast.Name) and e.id in ("ImportError", "ModuleNotFoundError", "Exception")
                                                              for e in ast.walk(h.type)) for h in node.handlers):
      for stmt in node.body:
        lines |= {n.lineno for n in ast.walk(stmt) if hasattr(n, "lineno")}
  return lines


def resolve_relative(path: Path, node: ast.ImportFrom) -> str | None:
  for pkg, base in PACKAGES.items():
    if base in path.parents:
      parts = [pkg, *path.relative_to(base).with_suffix("").parts]
      parts = parts[:len(parts) - node.level]  # the file itself, then each extra level up
      return ".".join(parts + ([node.module] if node.module else []))
  return None


def check_file(path: Path, errors: list[str]) -> None:
  try:
    tree = ast.parse(path.read_text(errors="replace"))
  except SyntaxError as e:
    errors.append(f"syntax {path.relative_to(ROOT)}:{e.lineno}")
    return
  skip = optional_lines(tree)
  rel = path.relative_to(ROOT)
  for node in ast.walk(tree):
    if getattr(node, "lineno", None) in skip:
      continue
    if isinstance(node, ast.Import):
      for a in node.names:
        if a.name.split(".")[0] in PACKAGES and module_path(a.name) is None:
          errors.append(f"I1 {rel}:{node.lineno} import {a.name}")
    elif isinstance(node, ast.ImportFrom):
      mod = resolve_relative(path, node) if node.level else node.module
      if not mod or mod.split(".")[0] not in PACKAGES:
        continue
      target = module_path(mod)
      if target is None:
        errors.append(f"I1 {rel}:{node.lineno} from {mod}")
        continue
      names = top_names(target)
      for a in node.names:
        if a.name != "*" and module_path(f"{mod}.{a.name}") is None and names is not None and a.name not in names:
          errors.append(f"I2 {rel}:{node.lineno} from {mod} import {a.name}")


def check_processes(errors: list[str]) -> None:
  for path in PROCESS_FILES:
    for node in ast.walk(ast.parse(path.read_text())):
      if isinstance(node, ast.Call) and getattr(node.func, "id", "") in ("PythonProcess", "NativeProcess", "DaemonProcess") and len(node.args) > 1:
        arg = node.args[1]
        if not (isinstance(arg, ast.Constant) and isinstance(arg.value, str)):
          continue
        if getattr(node.func, "id") == "NativeProcess":
          if not (ROOT / arg.value).is_dir():
            errors.append(f"I3 {path.relative_to(ROOT)}:{node.lineno} native dir {arg.value}")
        elif module_path(arg.value) is None:
          errors.append(f"I3 {path.relative_to(ROOT)}:{node.lineno} module {arg.value}")


def main() -> int:
  """With --baseline <json>, fail only on errors that the baseline run did not already report."""
  known = set(json.loads(Path(sys.argv[2]).read_text())["errors"]) if sys.argv[1:2] == ["--baseline"] else set()
  errors: list[str] = []
  files = sorted({p for d in SCAN if d.is_dir() for p in d.rglob("*.py") if "__pycache__" not in p.parts and ".git" not in p.parts})
  for path in files:
    check_file(path, errors)
  check_processes(errors)
  errors = [e for e in errors if not any(g in e for g in GENERATED)]
  new = [e for e in errors if e not in known]
  print(json.dumps({"files": len(files), "errors": errors, "new": new}, indent=1))
  return 1 if new else 0


if __name__ == "__main__":
  sys.exit(main())
