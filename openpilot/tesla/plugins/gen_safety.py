#!/usr/bin/env python3
"""Generate panda registry/param bits from opendbc/safety/plugins/safety.json; --check detects drift.
safety.json maps plugin id -> {header, param_bit, tx}. Each safety plugin owns one TX matching its C .msg.
The plugins themselves may live in the store (openpilot/tesla/store.py checks their claims against this file).
Built-in plugin can.tx claims must be declared here too. Stdlib only.
"""
import json
from pathlib import Path
import re
import sys

PLUGINS = Path(__file__).resolve().parent
HEADERS = PLUGINS.parents[2] / "opendbc_repo/opendbc/safety/plugins"
OUT = HEADERS / "registry.h"
DECLARED = HEADERS / "safety.json"

HELPERS = """static void safety_plugins_rx(const CANPacket_t *msg) {
  for (uint32_t i = 0U; i < SAFETY_PLUGINS_LEN; i++) {
    if (safety_plugins[i]->active()) {
      safety_plugins[i]->rx(msg);
    }
  }
}

// The active plugin that owns this TX message, or NULL.
static const safety_plugin *safety_plugin_for(const CANPacket_t *msg) {
  const safety_plugin *owner = NULL;
  for (uint32_t i = 0U; i < SAFETY_PLUGINS_LEN; i++) {
    const CanMsg *m = &safety_plugins[i]->msg;
    if ((owner == NULL) && msg_matches(msg, m->addr, m->bus, m->len) && safety_plugins[i]->active()) {
      owner = safety_plugins[i];
    }
  }
  return owner;
}

static void safety_plugins_reset(void) {
  for (uint32_t i = 0U; i < SAFETY_PLUGINS_LEN; i++) {
    safety_plugins[i]->reset();
  }
}
"""


def render() -> str:
  lines = ["#pragma once", "", "// Generated by openpilot/tesla/plugins/gen_safety.py. Do not edit.",
           '#include "opendbc/safety/plugins/plugin.h"']
  headers, bits, entries = set(), set(), []
  declared = json.loads(DECLARED.read_text())
  for path in sorted(PLUGINS.glob("*/plugin.json")):
    claims = {c[7:] for c in json.loads(path.read_text()).get("claims", []) if c.startswith("can.tx:")}
    if claims - set(declared.get(path.parent.name, {}).get("tx", [])):
      raise ValueError(f"{path}: can.tx claim not declared in {DECLARED.name}")
  for name, spec in sorted(declared.items()):
    path, tx = f"{DECLARED.name}:{name}", set(spec["tx"])
    header = spec["header"]
    bit = int(spec["param_bit"], 0)
    if not 0 < bit <= 0x8000 or bit & (bit - 1):
      raise ValueError(f"{path}: param_bit must be one uint16 bit")
    if bit in bits:
      raise ValueError(f"{path}: duplicate param_bit {bit:#x}")
    if not re.fullmatch(r"[a-z][a-z0-9_]*", name) or not re.fullmatch(r"[a-z][a-z0-9_]*[.]h", header):
      raise ValueError(f"{path}: invalid safety name/header")
    if header in headers:
      raise ValueError(f"{path}: duplicate safety header {header}")
    if not (HEADERS / header).is_file():
      raise ValueError(f"{path}: missing safety header {header}")
    if len(tx) != 1 or not all(re.fullmatch(r"0x[0-9A-Fa-f]{1,8}:[0-7]", t) for t in tx):
      raise ValueError(f"{path}: safety needs exactly one address:bus tx")
    addr, bus = next(iter(tx)).split(":")
    msg = re.search(r"[.]msg\s*=\s*\{(0x[0-9A-Fa-f]+|[0-9]+),\s*([0-7]),", (HEADERS / header).read_text())
    if msg is None or (int(msg[1], 0), int(msg[2])) != (int(addr, 16), int(bus)):
      raise ValueError(f"{path}: safety tx differs from header .msg")
    headers.add(header)
    bits.add(bit)
    lines += [f"#define XPILOT_PARAM_SP_{name.upper()} {bit:#06x}U", f'#include "opendbc/safety/plugins/{header}"']
    entries.append(f"  &{name}_plugin,")
  orphaned = {p.name for p in HEADERS.glob("*.h")} - {"plugin.h", "registry.h"} - headers
  if orphaned:
    raise ValueError(f"undeclared safety header: {sorted(orphaned)}")
  lines += ["", "static const safety_plugin *const safety_plugins[] = {", *entries, "};",
            "#define SAFETY_PLUGINS_LEN (sizeof(safety_plugins) / sizeof(safety_plugins[0]))", "", HELPERS.rstrip()]
  return "\n".join(lines) + "\n"


if __name__ == "__main__":
  text = render()
  if "--check" in sys.argv:
    if not OUT.exists() or OUT.read_text() != text:
      print(f"{OUT} is stale: run python3 openpilot/tesla/plugins/gen_safety.py")
      sys.exit(1)
  else:
    OUT.write_text(text)
