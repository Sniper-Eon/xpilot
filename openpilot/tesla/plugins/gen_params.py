#!/usr/bin/env python3
"""Generate openpilot/common/plugin_params.inc from every plugin's params.json (included by params_keys.h).

params.json: {"Key": {"type": "BOOL|INT|FLOAT|STRING|JSON|TIME|BYTES", "default": "0", "flags": "PERSISTENT | BACKUP"}}
"default", "flags" and "note" are optional (flags default to PERSISTENT | BACKUP; note is for humans). Run after editing a params.json and
commit the result; --check exits 1 when the committed file is stale (tools/sp_tesla_e2e/plugin_host_check.py).
"""
import json
from pathlib import Path
import sys

PLUGINS = Path(__file__).resolve().parent
OUT = PLUGINS.parents[1] / "common" / "plugin_params.inc"
TYPES = {"BOOL", "INT", "FLOAT", "STRING", "JSON", "TIME", "BYTES"}
FLAGS = {"PERSISTENT", "CLEAR_ON_MANAGER_START", "CLEAR_ON_ONROAD_TRANSITION", "CLEAR_ON_OFFROAD_TRANSITION", "DONT_LOG",
         "DEVELOPMENT_ONLY", "CLEAR_ON_IGNITION_ON", "BACKUP"}  # common/params.h ParamKeyFlag


def render() -> str:
  lines = ["// Generated by openpilot/tesla/plugins/gen_params.py from openpilot/tesla/plugins/*/params.json. Do not edit."]
  for f in sorted(PLUGINS.glob("*/params.json")):
    lines.append(f"// {f.parent.name}")
    for key, spec in json.loads(f.read_text()).items():
      flags = spec.get("flags", "PERSISTENT | BACKUP")
      if spec["type"] not in TYPES or not key.isidentifier() or not {x.strip() for x in flags.split("|")} <= FLAGS:
        raise ValueError(f"{f}: bad key, type or flags for {key}")
      default = f', {json.dumps(str(spec["default"]))}' if "default" in spec else ""
      lines.append(f'    {{"{key}", {{{flags}, {spec["type"]}{default}}}}},')
  return "\n".join(lines) + "\n"


if __name__ == "__main__":
  text = render()
  if "--check" in sys.argv:
    if not OUT.exists() or OUT.read_text() != text:
      print(f"{OUT} is stale: run python3 openpilot/tesla/plugins/gen_params.py")
      sys.exit(1)
  else:
    OUT.write_text(text)
